export interface VideoShowcaseItem {
  id: string;
  fileId: string;
  driveUrl: string;
  videoUrl?: string;
  thumbnailUrl: string;
  ariaLabel?: string;
  title?: string;
  description?: string;
}

/**
 * Helper to extract Google Drive file ID from a view/sharing URL or raw ID string.
 */
export function extractGoogleDriveFileId(urlOrId: string): string {
  if (!urlOrId) return "";
  const trimmed = urlOrId.trim();
  const fileMatch = trimmed.match(/\/file\/d\/([a-zA-Z0-9_-]+)/);
  if (fileMatch && fileMatch[1]) return fileMatch[1];
  const idMatch = trimmed.match(/[?&]id=([a-zA-Z0-9_-]+)/);
  if (idMatch && idMatch[1]) return idMatch[1];
  if (/^[a-zA-Z0-9_-]{25,50}$/.test(trimmed)) return trimmed;
  return "";
}

/**
 * Constructs the embeddable Google Drive preview URL (for iframe playback in modal).
 */
export function getGoogleDrivePreviewUrl(fileId: string): string {
  if (!fileId) return "";
  return `https://drive.google.com/file/d/${fileId}/preview`;
}

/**
 * Constructs the high-resolution thumbnail URL generated by Google Drive for a file ID.
 */
export function getGoogleDriveThumbnailUrl(fileId: string): string {
  if (!fileId) return "";
  return `https://lh3.googleusercontent.com/d/${fileId}=w1200`;
}

/**
 * Validates whether a video entry is populated with a real video source.
 */
export function isVideoPopulated(item: VideoShowcaseItem): boolean {
  if (!item) return false;
  const hasFileId = typeof item.fileId === "string" && item.fileId.trim() !== "";
  const hasDriveUrl = typeof item.driveUrl === "string" && item.driveUrl.trim() !== "";
  const hasVideoUrl = typeof item.videoUrl === "string" && item.videoUrl.trim() !== "";
  return hasFileId || hasDriveUrl || hasVideoUrl;
}

/**
 * Resolves the primary thumbnail URL for a video item.
 * Prioritizes local thumbnail, falls back to Google Drive thumbnail.
 */
export function resolveVideoThumbnail(item: VideoShowcaseItem): string {
  if (item.thumbnailUrl && item.thumbnailUrl.trim() !== "") {
    return item.thumbnailUrl;
  }
  const fileId = item.fileId || extractGoogleDriveFileId(item.driveUrl || item.videoUrl || "");
  if (fileId) {
    return getGoogleDriveThumbnailUrl(fileId);
  }
  return "";
}

/**
 * Resolves the playback target for an item:
 * - Google Drive embed iframe (default for drive links / IDs)
 * - HTML5 direct stream video (for local/direct MP4s)
 */
export function resolveVideoPlayback(item: VideoShowcaseItem): {
  type: "drive" | "direct";
  src: string;
  driveId?: string;
} {
  const fileId = item.fileId || extractGoogleDriveFileId(item.driveUrl || item.videoUrl || "");
  if (fileId) {
    return {
      type: "drive",
      src: getGoogleDrivePreviewUrl(fileId),
      driveId: fileId,
    };
  }
  return {
    type: "direct",
    src: item.videoUrl || "",
  };
}

